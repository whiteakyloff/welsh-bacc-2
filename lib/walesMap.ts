/** A coordinate in SVG units. */
export function mapPoint(lat: number, lng: number) {
    return {
        x: PADDING + (lng - WEST) * LON_SCALE * SCALE,
        y: PADDING + (NORTH - lat) * SCALE,
    };
}

/** A coordinate as percentages of the map box, for placing HTML over the SVG. */
export function mapPosition(lat: number, lng: number) {
    const { x, y } = mapPoint(lat, lng);
    return {
        left: `${(x / MAP_WIDTH) * 100}%`,
        top: `${(y / MAP_HEIGHT) * 100}%`,
    };
}
